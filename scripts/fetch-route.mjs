// Route pipeline: OSM road geometry + names -> data/route.json
// Traces the scenic Kingston->Ochi route through pinned waypoints using OSRM
// (routing over OpenStreetMap data), projects lat/lon to local meters,
// simplifies, and emits the polyline + named segments the game consumes.
// Usage: node scripts/fetch-route.mjs

import fs from 'node:fs';

// Waypoints pin the route to the scenic road (GAME_SPEC: V1 route decision).
// If OSRM snaps one badly (e.g. onto the toll highway), nudge its coords.
const WAYPOINTS = [
  { label: 'Norman Manley Intl Airport', lon: -76.7775, lat: 17.9357 },
  { label: 'Half Way Tree (Hope Rd approach)', lon: -76.7973, lat: 18.0109 },
  { label: 'Hagley Park Rd (west of HWT, avoids bus-terminal U-turn)', lon: -76.804, lat: 18.009 },
  { label: 'Walks Road / gorge approach', lon: -76.952, lat: 18.02 },
  { label: 'Bog Walk', lon: -77.005, lat: 18.1024 },
  { label: 'Linstead', lon: -77.0317, lat: 18.1368 },
  { label: 'Ewarton (Mt Rosser foot)', lon: -77.0701, lat: 18.1773 },
  { label: "Faith's Pen (old A1 over Mt Rosser)", lon: -77.0951, lat: 18.2347 },
  { label: 'Moneague (old road, north of town)', lon: -77.11, lat: 18.275 },
  { label: 'Walkers Wood (A3, snaps to Moneague-Ocho Rios Rd)', lon: -77.096, lat: 18.35 },
  { label: 'Fern Gully south end (A3)', lon: -77.101, lat: 18.37 },
  { label: "Dunn's River Falls", lon: -77.133, lat: 18.4125 },
];

const coords = WAYPOINTS.map((w) => `${w.lon},${w.lat}`).join(';');
const url = `https://router.project-osrm.org/route/v1/driving/${coords}?steps=true&geometries=geojson&overview=false`;

console.log('Fetching route from OSRM...');
const res = await fetch(url, { headers: { 'User-Agent': 'drive-jamaica-route-pipeline' } });
if (!res.ok) throw new Error(`OSRM ${res.status}: ${await res.text()}`);
const data = await res.json();
if (data.code !== 'Ok') throw new Error(`OSRM error: ${data.code}`);

// Concatenate step geometries, tracking the road name of every vertex.
const lonlat = [];
const names = [];
for (const leg of data.routes[0].legs) {
  for (const step of leg.steps) {
    for (const c of step.geometry.coordinates) {
      const prev = lonlat[lonlat.length - 1];
      if (prev && prev[0] === c[0] && prev[1] === c[1]) continue;
      lonlat.push(c);
      names.push(step.name || '');
    }
  }
}
console.log(`Raw vertices: ${lonlat.length}, distance: ${(data.routes[0].distance / 1000).toFixed(1)} km`);

// Equirectangular projection to local meters. North = -Z (matches car heading 0).
const [lon0, lat0] = lonlat[0];
const mLat = 110574;
const mLon = 111320 * Math.cos((lat0 * Math.PI) / 180);
const pts = lonlat.map(([lon, lat]) => [(lon - lon0) * mLon, -(lat - lat0) * mLat]);

// Douglas-Peucker simplification, keeping original indices for name lookup.
function simplify(points, first, last, tol2, keep) {
  let maxD = 0, idx = -1;
  const [ax, az] = points[first], [bx, bz] = points[last];
  const dx = bx - ax, dz = bz - az;
  const len2 = dx * dx + dz * dz || 1;
  for (let i = first + 1; i < last; i++) {
    const [px, pz] = points[i];
    const t = Math.max(0, Math.min(1, ((px - ax) * dx + (pz - az) * dz) / len2));
    const ddx = px - (ax + t * dx), ddz = pz - (az + t * dz);
    const d2 = ddx * ddx + ddz * ddz;
    if (d2 > maxD) { maxD = d2; idx = i; }
  }
  if (maxD > tol2) {
    simplify(points, first, idx, tol2, keep);
    keep.add(idx);
    simplify(points, idx, last, tol2, keep);
  }
}
const TOLERANCE = 6; // meters
const keep = new Set([0, pts.length - 1]);
simplify(pts, 0, pts.length - 1, TOLERANCE * TOLERANCE, keep);
const kept = [...keep].sort((a, b) => a - b);
console.log(`Simplified to ${kept.length} points (tolerance ${TOLERANCE} m)`);

// Named segments = runs of equal road names over the kept points.
// Unnamed stretches (roundabouts, links) merge into the preceding segment.
const points = kept.map((i) => [+pts[i][0].toFixed(1), +pts[i][1].toFixed(1)]);
const segments = [];
for (let k = 0; k < kept.length; k++) {
  const name = names[kept[k]];
  const cur = segments[segments.length - 1];
  if (cur && (name === '' || name === cur.name)) { cur.to = k + 1; continue; }
  if (name === '') continue; // unnamed before any named segment
  segments.push({ name, from: k, to: k + 1 });
}
console.log(`Segments: ${segments.length}`);
for (const s of segments) console.log(`  ${s.name} [${s.from}-${s.to}]`);

const out = {
  name: 'airport-run',
  comment: 'Generated by scripts/fetch-route.mjs from OpenStreetMap (via OSRM). Do not hand-edit.',
  source: 'OpenStreetMap contributors, routed via project-osrm.org',
  generated: new Date().toISOString(),
  distanceKm: +(data.routes[0].distance / 1000).toFixed(1),
  origin: { lon: lon0, lat: lat0 },
  points,
  segments,
};
fs.writeFileSync(new URL('../data/route.json', import.meta.url), JSON.stringify(out));
console.log(`Wrote data/route.json (${(JSON.stringify(out).length / 1024).toFixed(0)} kB)`);
