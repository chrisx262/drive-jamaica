// Shared deterministic PRNG (mulberry32). Seed with any 32-bit integer.
// Used by potholes, dogs, goats — each passes its own stable seed so
// scatter is independent and reproducible across sessions.
export function mulberry32(seed: number): () => number {
  let a = seed;
  return () => {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
